"""'Your resume at a glance': a summary filled in from fixed templates.

Nothing here is generated by a language model and nothing leaves Kareerly.
Each sentence is a template filled with values the system already holds:

1. skills: the resume's recognised skills, in the extractor's priority order;
2. experience level: the candidate's own Step 3 job-level answer (the resume
   itself is not read for a level);
3. best-fit roles: the top Fit-Now match titles, or, with no Fit-Now match,
   the top Aspiration titles (retrieved and ranked by the matcher).

``resume_version`` identifies the resume text the summary describes, so a
candidate's vote on one summary is never applied to a newer resume.
"""
from __future__ import annotations

import hashlib
from typing import Any, Dict, Iterable, List, Optional

SUMMARY_VERSION = "resume_summary_template_v1"
TOP_SKILLS = 5
SKILLS_IN_SENTENCE = 3
BEST_FIT_ROLES = 3

# Step 3 job-level answers (frontend/src/lib/preferenceOptions.ts jobLevelOptions).
EXPERIENCE_LEVELS: Dict[str, Dict[str, str]] = {
    "entry": {"label": "Entry level", "sentence": "You told us you're looking for entry-level work, such as a first job or a junior role."},
    "mid": {"label": "Mid level", "sentence": "You told us you're looking for mid-level roles, with 2 to 5 years of experience."},
    "senior": {"label": "Senior", "sentence": "You told us you're looking for senior roles, with 5 or more years of experience."},
}
UNSET_LEVEL = {"label": "Not set", "sentence": ""}

FEEDBACK_REASONS = ("missing_skills", "wrong_experience_level", "wrong_roles", "not_like_me", "something_else")


def resume_version(resume_text: str) -> str:
    normalized = " ".join(str(resume_text or "").split())
    return "sha256:" + hashlib.sha256(normalized.encode("utf-8")).hexdigest()[:24]


def _distinct(values: Iterable[Any], limit: int) -> List[str]:
    seen, result = set(), []
    for value in values:
        text = " ".join(str(value or "").split())
        if text and text.lower() not in seen:
            seen.add(text.lower())
            result.append(text)
        if len(result) == limit:
            break
    return result


def _join(items: List[str]) -> str:
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def experience_level(role_level: Optional[str]) -> Dict[str, str]:
    value = str(role_level or "").strip().lower()
    key = next((level for level in EXPERIENCE_LEVELS if value.startswith(level)), "")
    return {"value": key or "unset", "source": "step3_job_level", **(EXPERIENCE_LEVELS.get(key) or UNSET_LEVEL)}


def build_resume_summary(
    *,
    resume_text: str,
    skills: Iterable[Any],
    role_level: Optional[str] = None,
    fit_now_titles: Iterable[str] = (),
    aspiration_titles: Iterable[str] = (),
) -> Dict[str, Any]:
    """The card's sentences and facts; ``skills`` are names or {skill_name} records, best first."""
    names = [item.get("skill_name", "") if isinstance(item, dict) else item for item in skills]
    all_skills = _distinct(names, 10_000)
    top_skills = all_skills[:TOP_SKILLS]
    level = experience_level(role_level)
    fit_now = _distinct(fit_now_titles, BEST_FIT_ROLES)
    roles, roles_basis = (fit_now, "fit_now") if fit_now else (_distinct(aspiration_titles, BEST_FIT_ROLES), "aspiration")
    if not roles:
        roles_basis = "none"

    sentences = []
    if all_skills:
        count = len(all_skills)
        sentences.append(f"Your resume shows {count} skill{'s' if count != 1 else ''} we recognise, "
                         f"led by {_join(all_skills[:SKILLS_IN_SENTENCE])}.")
    else:
        sentences.append("Your resume doesn't list skills we recognise yet.")
    if level["sentence"]:
        sentences.append(level["sentence"])
    if roles_basis == "fit_now":
        sentences.append(f"Your best fit{'s' if len(roles) != 1 else ''} right now "
                         f"{'are' if len(roles) != 1 else 'is'} {_join(roles)}.")
    elif roles_basis == "aspiration":
        sentences.append(f"Your closest role{'s' if len(roles) != 1 else ''} right now "
                         f"{'are' if len(roles) != 1 else 'is'} {_join(roles)}, though {'none is' if len(roles) != 1 else 'it is not'} a Fit-Now match yet.")
    else:
        sentences.append("Your best-fit roles appear here once you have job matches.")

    return {
        "summary_version": SUMMARY_VERSION,
        "resume_version": resume_version(resume_text),
        "sentences": sentences,
        "summary": " ".join(sentences),
        "top_skills": top_skills,
        "experience_level": {key: value for key, value in level.items() if key != "sentence"},
        "best_fit_roles": roles,
        "roles_basis": roles_basis,
        "feedback_reasons": list(FEEDBACK_REASONS),
    }
