"""Bring the live Supabase job skills in line with the reviewed reference jobs.

The 2026-09-24 data review (docs/job-data-anomalies.md) removed implausible
skills from backend/data/reference_jobs.csv, such as Python and JavaScript on
the Accounting Assistant, "Identify requirements of the work in the artistic
performance" on the Digital Project Manager and Bookkeeping on the Business
Intelligence Developer. Matching reads Supabase first and the CSV only as a
fallback, so a live ``internal_jobs`` row that was loaded before the review
still carries the old skills. Every candidate is then compared with them: a
job lists skills its posting never asks for, the dashboard shows those skills
as matched or missing, and they become skill gaps.

This script only reads. It compares each live job whose ``job_id`` is in the
reference CSV with the reviewed skill lists and writes guarded SQL: a row is
updated only if it still holds the value that was read, so a job edited since
is left alone. It also lists live jobs (any ID) that point at skill IDs no job
may use: unknown IDs and unreviewed ``auto_generated_review`` rows.

    python3 -m backend.scripts.sync_reviewed_job_skills --output /tmp/job-skill-sync
    python3 -m backend.scripts.sync_reviewed_job_skills --jobs-json saved_internal_jobs.json --output /tmp/job-skill-sync

Review the SQL, then run it in the Supabase SQL editor.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path
from typing import Any, Dict, Iterable, List

BACKEND_DIR = Path(__file__).resolve().parents[1]
REFERENCE_JOBS_PATH = BACKEND_DIR / "data" / "reference_jobs.csv"
SKILLS_REFERENCE_PATH = BACKEND_DIR / "data" / "skills_reference.csv"
UNREVIEWED_STATUS = "auto_generated_review"


def split_ids(value: Any) -> List[str]:
    return list(dict.fromkeys(re.findall(r"\bSK(?:\d+|_[A-Z0-9_]+)\b", str(value or "").upper())))


def _names(value: Any) -> str:
    parts = [part.strip() for part in re.split(r"[;\n]", str(value or "")) if part.strip()]
    return "; ".join(dict.fromkeys(parts))


def _sql_text(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _guard(column: str, value: Any) -> str:
    return f"{column} is not distinct from " + ("null" if value in (None, "") else _sql_text(str(value)))


def plan_updates(live_jobs: Iterable[Dict[str, Any]], reference_jobs: Iterable[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """One planned update per live job whose skill IDs differ from its reviewed reference row."""
    reviewed = {row["job_id"].strip(): row for row in reference_jobs if str(row.get("job_id", "")).strip()}
    updates = []
    for job in live_jobs:
        job_id = str(job.get("job_id") or "").strip()
        reference = reviewed.get(job_id)
        if not reference:
            continue
        new_ids = split_ids(reference.get("required_skill_ids"))
        if not new_ids or split_ids(job.get("must_have_skill_ids")) == new_ids:
            continue
        updates.append({
            "job_id": job_id,
            "job_title": job.get("job_title") or reference.get("job_title", ""),
            "old_ids": job.get("must_have_skill_ids") or "",
            "old_required": job.get("required_skills") or "",
            "old_preferred": job.get("preferred_skills") or "",
            "new_ids": ";".join(new_ids),
            "new_required": _names(reference.get("mapped_required_skill_names")),
            "new_preferred": _names(reference.get("mapped_nice_to_have_skill_names")),
        })
    return updates


def unusable_skill_ids(live_jobs: Iterable[Dict[str, Any]], skill_status: Dict[str, str]) -> List[Dict[str, Any]]:
    """Live jobs that require a taxonomy ID that is unknown or was never reviewed.

    Legacy ``SK_*`` IDs are compared by name in matching and are not listed.
    """
    findings = []
    for job in live_jobs:
        for skill_id in split_ids(job.get("must_have_skill_ids")):
            if skill_id.startswith("SK_"):
                continue
            status = skill_status.get(skill_id)
            if status is None or status == UNREVIEWED_STATUS:
                findings.append({"job_id": job.get("job_id", ""), "job_title": job.get("job_title", ""),
                                 "skill_id": skill_id, "problem": "unknown_skill_id" if status is None else "unreviewed_skill"})
    return findings


def update_sql(updates: List[Dict[str, Any]], table: str = "internal_jobs") -> str:
    lines = [
        "-- Generated by scripts/sync_reviewed_job_skills.py. Review before running.",
        "-- Each update applies only if the row still holds the values that were read.",
        "begin;",
    ]
    for update in updates:
        lines.append(
            f"update public.{table} set must_have_skill_ids = {_sql_text(update['new_ids'])}, "
            f"required_skills = {_sql_text(update['new_required'])}, "
            f"preferred_skills = {_sql_text(update['new_preferred']) if update['new_preferred'] else 'null'}, "
            f"updated_at = now() "
            f"where job_id = {_sql_text(update['job_id'])} and {_guard('must_have_skill_ids', update['old_ids'])};"
            f"  -- {' '.join(str(update['job_title']).split())}"
        )
    lines.append("commit;")
    return "\n".join(lines) + "\n"


def _read_csv(path: Path) -> List[Dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--jobs-json", type=Path, help="Saved internal_jobs rows instead of reading Supabase")
    args = parser.parse_args(argv)

    if args.jobs_json:
        live_jobs = json.loads(args.jobs_json.read_text(encoding="utf-8"))
    else:
        from backend.app.services.supabase_jobs import fetch_internal_jobs

        live_jobs = fetch_internal_jobs(limit=5000)
    if not live_jobs:
        raise SystemExit("! no live jobs were read (Supabase unreachable or empty); pass --jobs-json")

    skill_status = {row["skill_id"].strip().upper(): row.get("mapping_status", "").strip()
                    for row in _read_csv(SKILLS_REFERENCE_PATH)}
    updates = plan_updates(live_jobs, _read_csv(REFERENCE_JOBS_PATH))
    findings = unusable_skill_ids(live_jobs, skill_status)

    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "internal_jobs_skill_sync.sql").write_text(update_sql(updates), encoding="utf-8")
    with (args.output / "unusable_job_skill_ids.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["job_id", "job_title", "skill_id", "problem"])
        writer.writeheader()
        writer.writerows(findings)
    print(f"{len(live_jobs)} live jobs read; {len(updates)} differ from the reviewed reference skills; "
          f"{len(findings)} use an unknown or unreviewed skill ID. Output in {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
